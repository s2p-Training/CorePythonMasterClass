
# Type Conversion Method For String
if __name__ == '__main__':

    s_data1 = str(10)
    print(s_data1)
    print(type(s_data1))

    s_data2 = str(-10)
    print(s_data2)
    print(type(s_data2))

    s_data3 = str(12.122)
    print(s_data3)
    print(type(s_data3))

    s_data4 = str(2e-4)
    print(type(s_data4))

    s_data5 = str(False)
    print(type(s_data5))

    s_data6 = str(2-4j)
    print(s_data6)
    print(type(s_data6))

