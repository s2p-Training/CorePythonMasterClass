# Type Conversion Methods For Integer
if __name__ == '__main__':

    i_num1 = int(16.59)
    print(i_num1)

    i_num2 = int(0b1010)
    print(i_num2)

    i_num3 = int(0o17)
    print(i_num3)

    i_num4 = int(0xa1)
    print(i_num4)

    i_num5 = int("1200")
    print(i_num5)

    i_num6 = int(True)
    print(i_num6)

    i_num7 = int("0b1111",2)
    print(i_num7)

    i_num8 = int("0o16",8)
    print(i_num8)

    i_num9 = int("0xa3",16)
    print(i_num9)

    i_num10 = int("4555",10)
    print(i_num10)
