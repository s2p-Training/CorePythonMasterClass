
# Type Conversion Methods In complex
if __name__ == '__main__':

    img_num1 = complex(10)
    print(img_num1)

    img_num2 = complex(-12.5)
    print(img_num2)

    img_num3 = complex(True)
    print(img_num3)

    img_num4 = complex(False)
    print(img_num4)

    img_num5 = complex("2+4j")
    print(img_num5)

    